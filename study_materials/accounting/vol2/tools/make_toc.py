#!/usr/bin/env python3
"""Write `_toc.typ` from the outline of a built PDF.

The Contents page is a real two-column table rather than a `outline()` call,
so that the line height is predictable and a 150-entry contents list fits on
one page. Page numbers therefore have to be baked in: build.py compiles,
reads the outline, writes the table, and compiles again until it is stable.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent

# Front-matter headings that should not appear in the printed contents.
SKIP_TITLES = {
    "Table of Contents",
}

# The printed contents begins with Chapter 1: the front matter is described in
# the "Where Everything Is" table, and repeating it here pushes the last of the
# appendices onto a second, nearly empty page.
START_AT = "Chapter 1:"


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("[", "\\[").replace("]", "\\]")


# Appendix sections D to I are short reference blocks; listing each one in the
# printed contents would push the last third of the list onto a second page.
SKIP_SUB_PREFIXES = ("D.", "E.", "F.", "G.", "H.", "I.")


def build_rows(pdf: Path) -> list[tuple[int, str, int]]:
    import pymupdf

    doc = pymupdf.open(pdf)
    toc = doc.get_toc()
    rows, started = [], False
    for level, title, page in toc:
        if level > 2:
            continue
        if not started:
            if title.startswith(START_AT):
                started = True
            else:
                continue
        if title in SKIP_TITLES:
            continue
        if level == 2 and title.startswith(SKIP_SUB_PREFIXES):
            continue
        rows.append((level, title, page))
    doc.close()
    return rows


def write_toc(rows: list[tuple[int, str, int]]) -> str:
    body = ["// Generated by tools/make_toc.py — do not edit by hand.", ""]
    body.append("#let toc-rows = (")
    for level, title, page in rows:
        body.append(f'  ({level}, "{esc(title)}", {page}),')
    body.append(")")
    text = "\n".join(body) + "\n"
    (OUT / "_toc.typ").write_text(text, encoding="utf-8")
    return text


def main() -> int:
    if len(sys.argv) < 2:
        print("usage: make_toc.py <pdf>")
        return 2
    pdf = Path(sys.argv[1])
    rows = build_rows(pdf)
    write_toc(rows)
    print(f"wrote _toc.typ: {len(rows)} entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
